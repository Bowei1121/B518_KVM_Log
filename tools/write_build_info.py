#!/usr/bin/env python3
"""Write host-app/_build_info.py: the version, git short hash and build date shown in the Monitor UI (issue #115).

CI runs this before PyInstaller; build_exe.bat runs it for the on-site build. The file is generated and
not committed (see .gitignore), so a plain source run keeps showing ``build dev``.
"""

from __future__ import annotations

import datetime
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "host-app" / "_build_info.py"


def git_short_hash() -> str:
    try:
        out = subprocess.run(["git", "rev-parse", "--short=7", "HEAD"], cwd=ROOT, capture_output=True,
                             text=True, check=True)
        return out.stdout.strip() or "dev"
    except (OSError, subprocess.CalledProcessError):
        return "dev"


def main() -> None:
    version = (ROOT / "host-app" / "VERSION").read_text(encoding="utf-8").strip()
    build_hash = git_short_hash()
    build_date = datetime.date.today().isoformat()
    OUT.write_text(
        '"""Generated by tools/write_build_info.py. Do not edit."""\n'
        f'VERSION = "{version}"\n'
        f'BUILD_HASH = "{build_hash}"\n'
        f'BUILD_DATE = "{build_date}"\n',
        encoding="utf-8",
    )
    print(f"wrote {OUT.name}: v{version} build {build_hash} {build_date}")


if __name__ == "__main__":
    main()
